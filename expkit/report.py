def _threshold_phrase(rows: list[dict], action: str) -> str:
    same = [r for r in rows if r["action"] == action]
    other = [r for r in rows if r["action"] != action]
    if not other:
        return (
            f"The call is the same ({_action_text(action)}) for every threshold from "
            f"{pp(rows[0]['threshold'], 2)} to {pp(rows[-1]['threshold'], 2)}."
        )
    flips = "; ".join(f"{pp(r['threshold'], 2)}: {_action_text(r['action'])}" for r in other)
    kept = ", ".join(pp(r["threshold"], 2) for r in same)
    return f"The call is {_action_text(action)} at {kept or 'none of the tested thresholds'}, but changes at {flips}."


