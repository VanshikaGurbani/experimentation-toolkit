"""Turn results.json into docs/RESULTS.md, docs/MEMO.md, figures and the README headline.

No number is typed by hand here: every value is read from the results file. Only wording is
fixed, and the wording is chosen by the decision recorded in the results.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

MODEL_LABELS = {
    "response_model": "Response model (ignores treatment)",
    "s_learner": "S-learner (LightGBM)",
    "t_learner": "T-learner (LightGBM)",
    "causal_forest": "Causal forest (EconML)",
}
HEADLINE_RE = re.compile(r"<!-- HEADLINE:START -->.*?<!-- HEADLINE:END -->", re.S)


def pct(x: float, d: int = 2) -> str:
    return f"{x * 100:.{d}f}%"


def pp(x: float, d: int = 2) -> str:
    return f"{x * 100:+.{d}f} pp"


def n_(x: float) -> str:
    return f"{int(round(x)):,}"


def ci_pct(lo: float, hi: float, d: int = 2) -> str:
    return f"{pct(lo, d)} to {pct(hi, d)}"


def ci_pp(lo: float, hi: float, d: int = 2) -> str:
    return f"{lo * 100:+.{d}f} to {hi * 100:+.{d}f} pp"


def pval(p: float) -> str:
    return "< 1e-300" if p < 1e-300 else (f"{p:.2e}" if p < 1e-4 else f"{p:.4f}")


def peq(p: float) -> str:
    """For sentences: 'p < 1e-300' or 'p = 0.0123'."""
    return pval(p) if p < 1e-300 else f"= {pval(p)}"


def scale_text(scale: float | None) -> str:
    if not scale:
        return "n/a"
    if scale > 100:
        return "more than 100x (effectively undecidable)"
    return f"{scale:.1f}x current sample"


def table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def _per100(x: float, d: int = 3) -> str:
    return f"{x * 100:.{d}f}"


# ---------------------------------------------------------------- figures


def make_figures(res: dict, fig_dir: Path) -> dict[str, str]:
    fig_dir.mkdir(parents=True, exist_ok=True)
    out = {}

    test = res["uplift"]["test"]
    fig, ax = plt.subplots(figsize=(6.4, 4.2))
    colors = {"response_model": "#9a9a9a", "s_learner": "#e08a3c", "t_learner": "#2a6fb0"}
    for name, row in test.items():
        ax.plot(
            [x * 100 for x in row["curve_x"]], [q * 100 for q in row["curve_q"]],
            label=MODEL_LABELS[name], color=colors[name], lw=2,
        )  # fmt: skip
    ate = next(iter(test.values()))["ate"]
    ax.plot([0, 100], [0, ate * 100], "k--", lw=1, label="Random targeting")
    ax.set_xlabel("Share of users targeted (%), highest predicted uplift first")
    ax.set_ylabel("Extra visits per 100 users in population")
    ax.set_title("Qini curves on the held-out test split")
    ax.legend(fontsize=8, frameon=False)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(fig_dir / "qini.png", dpi=140)
    plt.close(fig)
    out["qini"] = "results/qini.png"

    dec = res["uplift"]["deciles_selected_model"]
    fig, ax = plt.subplots(figsize=(6.4, 3.6))
    ax.bar(dec["decile"], [u * 100 for u in dec["uplift"]], color="#2a6fb0")
    ax.axhline(
        res["effect"]["visit"]["diff"] * 100, color="k", ls="--", lw=1, label="Average effect"
    )
    ax.set_xlabel("Score decile (1 = highest predicted uplift)")
    ax.set_ylabel("Measured lift in visit rate (pp)")
    ax.set_xticks(dec["decile"])
    ax.legend(frameon=False, fontsize=8)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(fig_dir / "deciles.png", dpi=140)
    plt.close(fig)
    out["deciles"] = "results/deciles.png"

    pw = res["power"]["curve"]
    fig, ax = plt.subplots(figsize=(6.4, 3.6))
    ax.plot(pw["n_per_arm"], [p * 100 for p in pw["power"]], color="#2a6fb0", lw=2)
    ax.axhline(80, color="k", ls="--", lw=1)
    ax.set_xscale("log")
    ax.set_xlabel("Users per arm (log scale)")
    ax.set_ylabel("Power (%)")
    ax.set_title("Power to detect the measured lift, equal arms")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(fig_dir / "power.png", dpi=140)
    plt.close(fig)
    out["power"] = "results/power.png"
    return out


# ---------------------------------------------------------------- RESULTS.md


def _action_text(a: str) -> str:
    return {
        "SHIP": "ship",
        "DONT_SHIP": "do not ship",
        "RUN_LONGER": "run longer",
        "INVALID": "invalid (do not decide)",
    }[a]


def build_results_md(res: dict, figs: dict[str, str]) -> str:
    m, d, e, p = res["meta"], res["design"], res["effect"], res["power"]
    c = e["conversion"]
    L: list[str] = []
    A = L.append
    A("# Results\n")
    A(
        "Generated by `expkit run-all` from `docs/results/results.json`. Do not edit by hand: "
        "every number below was produced by code.\n"
    )
    A(
        f"- Dataset: **{m['dataset']}**, {n_(d['arms']['control']['n'] + d['arms']['treatment']['n'])} users"
    )
    A(
        f"- Code version: `{(m['git_commit'] or 'unknown')[:10]}`, Python {m['python']}, seed {m['seed']}"
    )
    A(f"- Packages: {', '.join(f'{k} {val}' for k, val in m['packages'].items())}")
    A(f"- Full run time: {m['runtime_seconds'] / 60:.1f} minutes\n")

    A("## 1. Is the experiment trustworthy?\n")
    ctl, trt = d["arms"]["control"], d["arms"]["treatment"]
    A(
        table(
            ["Arm", "Users", "Share", "Visits", "Conversions", "Saw the ad"],
            [
                [
                    "Control",
                    n_(ctl["n"]),
                    pct(1 - d["srm"]["observed_treated_share"]),
                    n_(ctl["visits"]),
                    n_(ctl["conversions"]),
                    "n/a",
                ],
                [
                    "Treatment",
                    n_(trt["n"]),
                    pct(d["srm"]["observed_treated_share"]),
                    n_(trt["visits"]),
                    n_(trt["conversions"]),
                    f"{n_(trt['exposed'])} ({pct(e['exposed_share_of_treated'])})",
                ],
            ],
        )  # fmt: skip
    )
    A("")
    s = d["srm"]
    A(
        f"**Sample ratio mismatch (SRM).** Designed split 15% control and 85% treatment. "
        f"Chi-square = {s['chi2']:.3f}, p {peq(s['p_value'])}, alarm threshold p < 0.001. "
        f"Result: **{'FLAGGED' if s['flagged'] else 'passes'}**. "
        "The 85% / 15% design is the dataset's documented allocation, so it is an assumption "
        "about the design, not something the file proves.\n"
    )
    A("How well would this check catch lost data (counts-only arithmetic):\n")
    A(
        table(
            ["Total users", "Treated users lost", "p-value", "Flagged"],
            [
                [
                    n_(r["total_users"]),
                    pct(r["treated_lost_share"], 1),
                    pval(r["p_value"]),
                    "yes" if r["flagged"] else "no",
                ]
                for r in d["srm_sensitivity"]
            ],
        )  # fmt: skip
    )
    A("")
    bal = e["balance"]
    A(
        f"**Randomization balance.** Largest absolute standardized mean difference across the 12 "
        f"features: {d['max_abs_smd']:.4f} (values under 0.1 are usually read as balanced). "
        f"That summary hides a subtler problem. A LightGBM model trained on the train split to "
        f"predict who was treated from the 12 features reaches an AUC of **{pct(bal['auc'], 2)}** "
        f"on the test split ({n_(bal['n_test'])} users); a clean randomized experiment gives 50%. "
        f"The standard error of the AUC under pure randomization is {pct(bal['null_se'], 3)}, so "
        f"z = {bal['z']:.1f} and p {peq(bal['p_value'])}. Balance check at p < 0.001: "
        f"**{'FLAGGED' if bal['flagged'] else 'passes'}**. "
        + (
            "The imbalance is small in size (the model barely beats a coin flip) but far beyond "
            "chance, and it matters because the users who differ are not equally likely to visit.\n"
            if bal["flagged"]
            else "No evidence that the features predict assignment.\n"
        )
    )

    A("## 2. What did the treatment do?\n")
    A(
        "Intent-to-treat: every user assigned to treatment is counted, whether or not they saw the ad. "
        "A pre-specified rule picks the primary estimate: if the balance check above flags, the "
        "covariate-adjusted estimate is primary, otherwise the raw difference is. "
        f"Basis used here: **{e['primary_basis']}**. The adjusted estimate is a doubly robust AIPW "
        "estimate computed on the test split with models fitted on the train split; the raw "
        "difference in means uses all users.\n"
    )
    A(
        table(
            [
                "Metric",
                "Control",
                "Treatment",
                "Absolute lift (95% CI)",
                "Relative lift (95% CI)",
                "p-value",
            ],
            [
                [
                    name,
                    pct(x["mean_control"], 3),
                    pct(x["mean_treatment"], 3),
                    f"{pp(x['diff'], 3)} ({ci_pp(x['ci_low'], x['ci_high'], 3)})",
                    f"{x['rel_lift'] * 100:+.1f}% ({x['rel_ci_low'] * 100:+.1f}% to {x['rel_ci_high'] * 100:+.1f}%)",
                    pval(x["p_value"]),
                ]
                for name, x in (
                    ("Visit rate, raw difference", e["visit_raw"]),
                    ("Visit rate, covariate-adjusted (AIPW)", e["visit_adjusted"]),
                    ("Conversion rate, raw difference (secondary)", c),
                )
            ],
        )  # fmt: skip
    )
    A("")
    raw_v, adj_v = e["visit_raw"], e["visit_adjusted"]
    gap = raw_v["diff"] - adj_v["diff"]
    ratio = abs(gap) / max(raw_v["se"], adj_v["se"])
    A(
        f"The raw lift is {pp(raw_v['diff'], 3)} and the adjusted lift is {pp(adj_v['diff'], 3)}: "
        f"adjusting {'lowers' if gap > 0 else 'raises'} the estimate by {abs(gap) * 100:.3f} pp, "
        f"which is {ratio:.1f} times the larger of the two standard errors (under clean "
        f"randomization the two should agree within about 2). The conversion rate has no adjusted "
        f"estimate in this run, so it is shown raw and should be read with the same caution.\n"
    )
    A(
        f"**Decision rule.** Practical threshold (assumption, see `expkit/config.py`): "
        f"{pp(e['practical_threshold'], 2)} on visit rate. The rule ships only if the whole 95% "
        f"interval is at or above the threshold, does not ship if the whole interval is below it, "
        f"and otherwise runs longer. On the primary ({e['primary_basis']}) estimate: "
        f"**{_action_text(e['decision']['action'])}**; on the raw estimate: "
        f"**{_action_text(e['decision_raw']['action'])}**. With the conversion rate as a guardrail "
        f"(no drop allowed): **{_action_text(e['decision_with_conversion_guardrail']['action'])}**.\n"
    )
    A("How the decision depends on the threshold:\n")
    A(
        table(
            [
                "Threshold (visit rate lift)",
                "Decision on primary estimate",
                "Data scale needed if undecided",
                "Decision on raw estimate",
            ],
            [
                [
                    pp(r["threshold"], 2),
                    _action_text(r["action"]),
                    scale_text(r["sample_scale"]),
                    _action_text(r["action_raw"]),
                ]
                for r in e["threshold_sensitivity"]
            ],
        )  # fmt: skip
    )
    A("")

    A("## 3. Power and sample size calculator\n")
    A(
        f"Baseline = control visit rate {pct(p['baseline_rate'], 3)}, two-sided alpha 5%, power 80%. "
        f"The real experiment used an {d['arms']['treatment']['n'] / d['arms']['control']['n']:.2f}:1 "
        f"treatment to control allocation, so totals are shown for a 50/50 split and for the "
        f"actual ratio.\n"
    )
    A(
        table(
            [
                "Effect to detect",
                "Absolute",
                "Users per arm (50/50)",
                "Total (50/50)",
                "Total (85/15)",
            ],
            [
                [
                    r["label"],
                    pp(r["absolute_effect"], 3),
                    n_(r["n_per_arm_equal"]),
                    n_(r["total_equal"]),
                    n_(r["total_85_15"]),
                ]
                for r in p["table"]
            ],
        )  # fmt: skip
    )
    A("")
    A(
        f"With the actual arm sizes ({n_(ctl['n'])} control, {n_(trt['n'])} treatment) the smallest "
        f"lift this experiment could detect with 80% power is {pp(p['mde_of_actual_experiment'], 3)}.\n"
    )
    A(f"![Power curve]({figs['power']})\n")

    A("## 4. Do the toolkit's own checks hold up on real rows?\n")
    val = res["validation"]
    aa = val["aa"]
    A(
        f"**A/A test.** The treated arm was split at random into two halves of {n_(aa['n_per_arm'])} "
        f"users, {n_(aa['reps'])} times. The test at 5% should reject about 5% of the time. "
        f"Measured false positive rate: **{pct(aa['false_positive_rate'], 1)}** "
        f"(95% CI {ci_pct(*aa['ci95'], 1)}).\n"
    )
    A("**Power calibration.** Samples of the calculator's size were drawn from the real arms:\n")
    A(
        table(
            [
                "Case",
                "Users per arm",
                "Power from the formula",
                "Measured power",
                "95% CI of measured",
                "Draws",
            ],
            [
                [
                    r["label"],
                    n_(r["n_per_arm"]),
                    pct(r["nominal_power"], 1),
                    pct(r["empirical_power"], 1),
                    ci_pct(*r["ci95"], 1),
                    n_(r["reps"]),
                ]
                for r in val["power"]
            ],
        )  # fmt: skip
    )
    A("")
    A(
        "The formula's inputs are the measured control rate and the measured lift, treated as the "
        "truth for this check.\n"
    )
    A(
        f"**Decision rule over repeated experiments.** Samples were drawn from the real arms at "
        f"multiples of the planned size ({n_(val['planned_n_per_arm'])} users per arm, 80% power for "
        f"the measured lift). The practical threshold is {pp(e['practical_threshold'], 2)}.\n"
    )
    A(
        table(
            ["Users per arm", "Ship", "Run longer", "Do not ship", "Draws"],
            [
                [
                    n_(r["n_per_arm"]),
                    pct(r["ship"], 1),
                    pct(r["run_longer"], 1),
                    pct(r["dont_ship"], 1),
                    n_(r["reps"]),
                ]
                for r in val["decision"]
            ],
        )  # fmt: skip
    )
    A("")
    A(
        "Being powered to detect the effect is not the same as being powered to clear a practical "
        "threshold: at the planned size the interval is usually still too wide to settle the decision.\n"
    )

    A("## 5. CUPED variance reduction\n")
    cr, hs = res["cuped"]["criteo"], res["cuped"]["hillstrom"]
    A(
        f"**Criteo, held-out test split ({n_(cr['n_test'])} users), outcome = visit.** "
        "The file has no pre-experiment version of the outcome, only 12 anonymized features, so "
        "the covariates are those features (linear) or a LightGBM prediction of visit trained on "
        "the train split (CUPAC). Adjustment weights were fitted on other splits.\n"
    )
    raw = cr["raw"]
    A(
        table(
            [
                "Method",
                "Lift estimate",
                "95% CI",
                "Standard error",
                "Variance reduction",
                "Sample needed vs no adjustment",
            ],
            [
                [
                    "No adjustment",
                    pp(raw["diff"], 3),
                    ci_pp(raw["ci_low"], raw["ci_high"], 3),
                    pct(raw["se"], 4),
                    "n/a",
                    "100%",
                ],
                *[
                    [
                        x["label"],
                        pp(x["diff"], 3),
                        ci_pp(x["ci_low"], x["ci_high"], 3),
                        pct(x["se"], 4),
                        pct(x["variance_reduction"], 1),
                        pct(x["sample_size_ratio"], 1),
                    ]
                    for x in (cr["linear"], cr["cupac"])
                ],
            ],
        )  # fmt: skip
    )
    A("")
    shifts = [(x["label"], x["diff"] - raw["diff"]) for x in (cr["linear"], cr["cupac"])]
    moved = max(abs(sh) for _, sh in shifts) > 3 * raw["se"]
    A(
        "Under clean randomization CUPED leaves the estimate where it was and only narrows the "
        "interval (the unit tests confirm this on simulated data). "
        + ("Here the estimate also moved: " if moved else "Here the estimate stayed close: ")
        + "; ".join(f"{lab} shifted it by {pp(sh, 3)}" for lab, sh in shifts)
        + f", against a standard error of {pct(raw['se'], 3)} for the raw estimate."
        + (
            " That is the covariate imbalance from section 1 showing up a second way. The "
            "variance reduction columns are still valid as measures of precision, but the lift "
            "columns should be read together with the adjusted estimate in section 2.\n"
            if moved
            else "\n"
        )
    )
    hr = hs["raw"]
    hc = hs["cuped"]
    A(
        f"**Hillstrom email test ({n_(hs['n'])} customers), outcome = spend per customer, covariate = "
        f"spend in the 12 months before the email.** Correlation between spend and prior spend: "
        f"{hs['corr_spend_history']:.3f}. SRM across the three arms (designed 1:1:1): "
        f"p {peq(hs['srm_p_value'])}, {'FLAGGED' if hs['srm_flagged'] else 'passes'}.\n"
    )
    A(
        table(
            [
                "Method",
                "Lift in spend per customer (95% CI)",
                "Standard error",
                "Variance reduction",
                "Sample needed vs no adjustment",
            ],
            [
                [
                    "No adjustment",
                    f"${hr['diff']:.3f} (${hr['ci_low']:.3f} to ${hr['ci_high']:.3f})",
                    f"${hr['se']:.4f}",
                    "n/a",
                    "100%",
                ],
                [
                    "CUPED",
                    f"${hc['diff']:.3f} (${hc['ci_low']:.3f} to ${hc['ci_high']:.3f})",
                    f"${hc['se']:.4f}",
                    pct(hc["variance_reduction"], 2),
                    pct(hc["sample_size_ratio"], 2),
                ],
            ],
        )  # fmt: skip
    )
    A("")

    A("## 6. Uplift modeling\n")
    u = res["uplift"]
    A(
        f"Outcome: visit. Models trained on the train split ({n_(u['n_train'])} users), early "
        f"stopping on the validation split ({n_(u['n_val'])}), all numbers below on the untouched "
        f"test split ({n_(u['n_test'])}). The Qini coefficient is the area between a model's Qini "
        f"curve and the random-targeting line, shown as extra visits per 100 users; the 95% "
        f"intervals come from {m['settings']['n_boot']} Poisson bootstrap replicates. "
        f"'Top 10%' is the share of all extra visits captured by treating only the 10% of users "
        f"the model ranks highest.\n"
    )
    rows = []
    for name, r in u["test"].items():
        diff_key = "qini_minus_response_model"
        diff = (
            f"{_per100(r[diff_key])} ({_per100(r[diff_key + '_ci95'][0])} to {_per100(r[diff_key + '_ci95'][1])})"
            if diff_key in r
            else "reference"
        )
        rows.append(
            [
                MODEL_LABELS[name],
                f"{_per100(r['qini_coefficient'])} ({_per100(r['qini_ci95'][0])} to {_per100(r['qini_ci95'][1])})",
                f"{pct(r['capture@0.1'], 1)} ({ci_pct(*r['capture@0.1_ci95'], 1)})",
                f"{pct(r['capture@0.3'], 1)} ({ci_pct(*r['capture@0.3_ci95'], 1)})",
                diff,
                f"{u['validation_qini'][name] * 100:.3f}",
            ]
        )
    A(
        table(
            [
                "Model",
                "Qini coefficient (95% CI)",
                "Top 10% captures",
                "Top 30% captures",
                "Qini minus response model (95% CI)",
                "Validation Qini",
            ],
            rows,
        )  # fmt: skip
    )
    A("")
    A(
        f"Model chosen on the validation split (not the test split): "
        f"**{MODEL_LABELS[u['selected_on_validation']]}**. "
        "A random ranking has a Qini coefficient of 0. The response model is the common mistake of "
        "targeting the users most likely to visit anyway. Because the top-ranked users can have "
        "negative uplift, capture shares above 100% are possible.\n"
    )
    A(f"![Qini curves]({figs['qini']})\n")
    if u.get("test_ipw"):
        A(
            "**Robustness to the arm imbalance.** The same curves recomputed with inverse "
            "propensity weights (point estimates only, same test split), so users who are "
            "over-represented in one arm count for less:\n"
        )
        A(
            table(
                ["Model", "Qini coefficient", "Top 10% captures", "Top 30% captures"],
                [
                    [
                        MODEL_LABELS[name],
                        _per100(r["qini_coefficient"]),
                        pct(r["capture@0.1"], 1),
                        pct(r["capture@0.3"], 1),
                    ]
                    for name, r in u["test_ipw"].items()
                ],
            )
        )
        A("")
    dec = u["deciles_selected_model"]
    A(
        f"Measured lift by score decile for {MODEL_LABELS[u['selected_on_validation']]} "
        "(SQL query `sql/06_uplift_deciles.sql`, test split):\n"
    )
    A(
        table(
            ["Decile", "Users", "Visit rate treated", "Visit rate control", "Measured lift"],
            [
                [
                    str(dec["decile"][i]),
                    n_(dec["n"][i]),
                    pct(dec["visit_rate_treated"][i], 2),
                    pct(dec["visit_rate_control"][i], 2),
                    pp(dec["uplift"][i], 2),
                ]
                for i in range(len(dec["decile"]))
            ],
        )  # fmt: skip
    )
    A("")
    A(f"![Lift by decile]({figs['deciles']})\n")

    cf = u["causal_forest"]
    A("### EconML causal forest comparison\n")
    if cf is None:
        A("Not run (the optional `econml` package was not installed).\n")
    else:
        A(
            f"Causal forests are slow, so the forest was fitted on a random {n_(cf['n_train'])}-user "
            f"subsample of the train split ({cf['fit_seconds']:.0f} s) and every model was compared on "
            f"the same random {n_(cf['n_eval'])}-user subset of the test split (forest scoring took "
            f"{cf['score_seconds']:.0f} s). The LightGBM models here use their full-data fits, so "
            "this table compares methods at different training sizes, and the wider intervals "
            "reflect the smaller evaluation set.\n"
        )
        rows = []
        for name, r in cf["eval_subset"].items():
            rows.append(
                [
                    MODEL_LABELS[name],
                    f"{_per100(r['qini_coefficient'])} ({_per100(r['qini_ci95'][0])} to {_per100(r['qini_ci95'][1])})",
                    f"{pct(r['capture@0.1'], 1)} ({ci_pct(*r['capture@0.1_ci95'], 1)})",
                    f"{pct(r['capture@0.3'], 1)} ({ci_pct(*r['capture@0.3_ci95'], 1)})",
                ]
            )
        A(
            table(
                ["Model", "Qini coefficient (95% CI)", "Top 10% captures", "Top 30% captures"], rows
            )
        )
        A("")

    A("## 7. Model fit times\n")
    A(
        table(
            ["Model", "Seconds"],
            [[MODEL_LABELS[k], f"{s:.0f}"] for k, s in u["fit_seconds"].items()],
        )
    )
    A("")
    return "\n".join(L)


