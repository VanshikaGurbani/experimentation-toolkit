def build_headline(res: dict) -> str:
    e, u, val, cr = res["effect"], res["uplift"], res["validation"], res["cuped"]["criteo"]
    v, raw, bal = e["visit"], e["visit_raw"], e["balance"]
    sel = u["selected_on_validation"]
    best = u["test"][sel]
    resp = u["test"]["response_model"]
    n_total = res["design"]["arms"]["control"]["n"] + res["design"]["arms"]["treatment"]["n"]
    vr = cr["cupac"]["variance_reduction"]
    cuped_phrase = (
        f"CUPAC cut the variance of the lift estimate by {pct(vr, 1)}"
        if vr > 0
        else "CUPAC did not reduce the variance of the lift estimate"
    )
    balance_phrase = (
        f"The sample ratio check {'FAILED' if res['design']['srm']['flagged'] else 'passed'}, but a "
        f"model can predict assignment from the features (AUC {pct(bal['auc'], 1)} against 50% "
        f"for a clean experiment), so the headline lift is the covariate-adjusted one and the raw "
        f"difference of {pp(raw['diff'], 2)} overstates it. "
        if bal["flagged"]
        else "The sample ratio and balance checks passed. "
    )
    return (
        "<!-- HEADLINE:START -->\n"
        f"On {n_(n_total)} users from the Criteo uplift experiment, the ad campaign raised the "
        f"visit rate by **{pp(v['diff'], 2)}** (95% CI {ci_pp(v['ci_low'], v['ci_high'], 2)}; "
        f"baseline {pct(v['mean_control'], 2)}). "
        f"{balance_phrase}"
        f"With a placeholder minimum worthwhile lift of {pp(e['practical_threshold'], 2)}, the "
        f"decision rule says **{_action_text(e['decision']['action'])}**. "
        f"Treating only the top 10% of users ranked by the {MODEL_LABELS[sel]} captures "
        f"{pct(best['capture@0.1'], 0)} of the extra visits, against {pct(resp['capture@0.1'], 0)} "
        f"for ranking by likelihood to visit. "
        f"The A/A false positive rate measured {pct(val['aa']['false_positive_rate'], 1)} against 5% "
        f"expected, and {cuped_phrase}.\n"
        "<!-- HEADLINE:END -->"
    )


def write_report(results_json: Path, out_dir: Path, readme: Path | None = None) -> None:
    res = json.loads(Path(results_json).read_text(encoding="utf-8"))
    out_dir = Path(out_dir)
    figs = make_figures(res, out_dir / "results")
    (out_dir / "RESULTS.md").write_text(build_results_md(res, figs) + "\n", encoding="utf-8")
    (out_dir / "MEMO.md").write_text(build_memo_md(res) + "\n", encoding="utf-8")
    if readme is not None and Path(readme).exists():
        text = Path(readme).read_text(encoding="utf-8")
        if HEADLINE_RE.search(text):
            Path(readme).write_text(
                HEADLINE_RE.sub(lambda _m: build_headline(res), text), encoding="utf-8"
            )
